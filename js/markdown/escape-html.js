/**
 * Escapes the characters that would otherwise be interpreted as HTML.
 * Used on every piece of user-authored text before it enters the page.
 */
export function escapeHtml(text) {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}
